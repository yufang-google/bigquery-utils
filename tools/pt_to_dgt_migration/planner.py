def _map_taxonomy_to_dg_tag_key(
    taxonomy: Any,
    target_dgt_project_id: str,
    space_replacement: str,
    collapse_spaces: bool,
    used_dg_tag_keys: set[str],
    collision_resolution: str = constants.COLLISION_RESOLUTION_COUNTER,
    colliding_base_names: set[str] | None = None,
) -> tuple[str, str, dict[str, Any]]:
  """Maps a single regional Data Catalog Taxonomy to a global DG Tag Key.

  Step-by-Step Algorithm & Collision Resolution:
  1. Sanitizes `taxonomy.display_name` via `sanitize_name` to form the candidate
     `dg_tag_key_short_name`.
  2. Resolves cross-region or same-region naming collisions within the global
     `target_dgt_project_id` namespace:
     - If `collision_resolution == "from_region"` and the sanitized base name
       appears more than once across the migration plan
       (`colliding_base_names`), appends `_from_<sanitized_location>`
       symmetrically to *every* colliding taxonomy (e.g., `PII_from_us` and
       `PII_from_eu`). Using `_from_<region>` rather than a bare `_<region>`
       suffix makes it clear that the global Tag Key's suffix reflects
       historical migration origin rather than a geographic restriction after
       Cross-Region Replication.
     - If a collision still exists in `used_dg_tag_keys` (either under the
       default `counter` strategy or when two taxonomies in the *same* region
       sanitize to the same name), appends `-1`, `-2`, ... until unique.
  3. Builds the `CREATE_DG_TAG_KEY` manifest action with `purpose =`
     `"DATA_GOVERNANCE"`, truncates `api_payload["description"]` to
     `MAX_TAG_DESCRIPTION_LENGTH` (256 chars) while keeping full provenance in
     `audit_lineage`, and attaches any `_validate_short_name` or taxonomy-level
     IAM warnings.

  Args:
      taxonomy: The `analyzer.TaxonomyInfo` object to map.
      target_dgt_project_id: Target GCP project ID where global DG Tag Keys are
        created.
      space_replacement: Replacement string for spaces (default: `"_"`).
      collapse_spaces: Whether to collapse consecutive spaces.
      used_dg_tag_keys: Mutable set tracking `<target_dgt_project_id>/<key>`
        namespaced names already allocated in the current plan.
      collision_resolution: Strategy for resolving Tag Key `short_name`
        collisions (`"counter"` or `"from_region"`).
      colliding_base_names: Optional pre-computed set of sanitized taxonomy
        names that occur multiple times across `analysis_results`.

  Returns:
      A 3-tuple `(dg_tag_key_short_name, namespaced_dg_tag_key,
      dg_tag_key_action)`:
      - `dg_tag_key_short_name`: Final unique Tag Key short name (e.g.,
        `"Sensitive_Data"`).
      - `namespaced_dg_tag_key`: Full namespaced Tag Key path (e.g.,
        `"my-dgt-project/Sensitive_Data"`).
      - `dg_tag_key_action`: `CREATE_DG_TAG_KEY` action dictionary for
        `phase_2_resource_manifest["taxonomies_to_dg_tag_keys"]`.
  """
  sanitized_taxonomy_name = sanitize_name(
      taxonomy.display_name,
      space_replacement=space_replacement,
      collapse_spaces=collapse_spaces,
  )
  dg_tag_key_short_name = sanitized_taxonomy_name
  namespaced_dg_tag_key = f"{target_dgt_project_id}/{dg_tag_key_short_name}"

  has_base_collision = (
      colliding_base_names is not None
      and sanitized_taxonomy_name in colliding_base_names
  ) or (namespaced_dg_tag_key in used_dg_tag_keys)

  # Apply symmetric `_from_<region>` provenance suffix when `from_region` is
  # selected and multiple taxonomies share the same sanitized display name.
  if (
      collision_resolution == constants.COLLISION_RESOLUTION_FROM_REGION
      and has_base_collision
  ):
    raw_location = getattr(taxonomy, "location", "") or "unknown"
    sanitized_location = sanitize_name(
        raw_location,
        space_replacement=space_replacement,
        collapse_spaces=collapse_spaces,
    )
    dg_tag_key_short_name = (
        f"{sanitized_taxonomy_name}_from_{sanitized_location}"
    )
    namespaced_dg_tag_key = f"{target_dgt_project_id}/{dg_tag_key_short_name}"

  # Resolve any remaining DG Tag Key collisions (default `counter` mode, or two
  # taxonomies in the same region whose names collide after space sanitization).
  counter = 1
  original_dg_tag_key_short_name = dg_tag_key_short_name
  while namespaced_dg_tag_key in used_dg_tag_keys:
    dg_tag_key_short_name = f"{original_dg_tag_key_short_name}-{counter}"
    namespaced_dg_tag_key = f"{target_dgt_project_id}/{dg_tag_key_short_name}"
    counter += 1

  used_dg_tag_keys.add(namespaced_dg_tag_key)

  taxonomy_location = getattr(taxonomy, "location", "")
  location_suffix = (
      f" (region: {taxonomy_location})" if taxonomy_location else ""
  )
  primary_description = (
      f"Migrated from Taxonomy: {taxonomy.display_name}{location_suffix}"
  )
  source_suffix = f"Source taxonomy: {taxonomy.name}"
  full_lineage = f"{primary_description} | {source_suffix}"
  dg_tag_key_payload = {
      "short_name": dg_tag_key_short_name,
      "parent": f"projects/{target_dgt_project_id}",
      "purpose": constants.TAG_PURPOSE_DATA_GOVERNANCE,
      "description": primary_description[
          : constants.MAX_TAG_DESCRIPTION_LENGTH
      ],
  }

  dg_tag_key_warnings = _validate_short_name(dg_tag_key_short_name)
  for warning in getattr(taxonomy, "warnings", []):
    if warning not in dg_tag_key_warnings:
      dg_tag_key_warnings.append(warning)
  dg_tag_key_action = {
      "namespaced_name": namespaced_dg_tag_key,
      "action": constants.ACTION_CREATE_DG_TAG_KEY,
      "api_payload": dg_tag_key_payload,
      "source_resource_name": taxonomy.name,
      "source_display_name": taxonomy.display_name,
      "source_taxonomy_region": taxonomy_location,
      "audit_lineage": full_lineage,
  }
  if dg_tag_key_warnings:
    dg_tag_key_action["warnings"] = dg_tag_key_warnings

  return dg_tag_key_short_name, namespaced_dg_tag_key, dg_tag_key_action


def _map_policy_tags_to_dg_tag_values(
    taxonomy: Any,
    target_project_id: str,
    dg_tag_key_short_name: str,
    namespaced_dg_tag_key: str,
    space_replacement: str,
    collapse_spaces: bool,
) -> tuple[
    dict[str, str], dict[str, str], list[dict[str, Any]], dict[str, Any]
]:
  """Maps Policy Tags in a Taxonomy to hierarchical DG Tag Values.

  How Hierarchy Reconstruction & Key-Wide Uniqueness Work:
  1. Sanitizes each Policy Tag's `display_name` via `sanitize_name` and groups
     tags by `parent_policy_tag` into an in-memory tree (`hierarchy` + `roots`).
     Any tag whose `parent_policy_tag` is empty or missing from the taxonomy
     (e.g., an orphaned reference) is treated as a root under the DG Tag Key so
     it is never silently dropped.
  2. Traverses the tree top-down from `roots` via `assign_names_and_add_to_plan`
     so parent `CREATE_DG_TAG_VALUE` actions always precede their child actions
     in `dg_tag_value_actions`.
  3. Enforces uniqueness of `actual_short_name` across the **entire DG Tag Key**
     (`assigned_short_names`), appending `-1`, `-2` on collision so that
     `phase_3_binding_map` (`{"dg_tag_key": ..., "dg_tag_value": short_name}`)
     and V2 Data Policy `data_governance_tag` references remain 100%
     unambiguous even in multi-level hierarchies.
  4. Detects "dangling" `fine_grained_readers` on Classification-Only
     (`is_access_control=False`) taxonomies and emits an explicit warning on the
     Tag Value action explaining that BigQuery currently ignores those IAM
     bindings (Default Allow) and that no V2 Data Policies will be synthesized
     unless Access Control enforcement is enabled on the source taxonomy.

  Args:
      taxonomy: The `analyzer.TaxonomyInfo` object containing `policy_tags`.
      target_project_id: Target GCP project ID where global DG Tags are created.
      dg_tag_key_short_name: Short name of the parent DG Tag Key.
      namespaced_dg_tag_key: Namespaced name of the parent DG Tag Key
        (`<target_project_id>/<dg_tag_key_short_name>`).
      space_replacement: Replacement string for spaces (default: `"_"`).
      collapse_spaces: Whether to collapse consecutive spaces.

  Returns:
      A 4-tuple `(policy_tag_short_names, policy_tag_display_paths,
      dg_tag_value_actions, bindings_map)`:
      - `policy_tag_short_names`: Dict mapping each source Policy Tag resource
        name (`projects/.../policyTags/...`) to its unique sanitized DG Tag
        Value `short_name`.
      - `policy_tag_display_paths`: Dict mapping each source Policy Tag resource
        name to its full hierarchical display path (`<Taxonomy> > <Parent> >`
        `<Child>`).
      - `dg_tag_value_actions`: Topologically ordered list of
        `CREATE_DG_TAG_VALUE` action dicts for Phase 2a, where each action's
        `namespaced_name` holds the full hierarchical DG Tag Value path
        (`<project>/<key>/<parent_val>/<child_val>`).
      - `bindings_map`: Dict for `phase_3_binding_map` mapping each source
        Policy Tag resource name to `{"dg_tag_key": ..., "dg_tag_value": ...}`.
  """
  policy_tag_short_names = {}
  for policy_tag in taxonomy.policy_tags:
    sanitized_policy_tag_name = sanitize_name(
        policy_tag.display_name,
        space_replacement=space_replacement,
        collapse_spaces=collapse_spaces,
    )
    policy_tag_short_names[policy_tag.name] = sanitized_policy_tag_name

  # Build in-memory parent-to-children adjacency list for hierarchical tags.
  hierarchy = collections.defaultdict(list)
  roots = []

  for policy_tag in taxonomy.policy_tags:
    # Verify that `parent_policy_tag` exists inside `policy_tag_short_names`
    # (i.e., belongs to the current taxonomy). If a tag references a missing or
    # external parent, promote it to `roots` so it is still visited and planned
    # rather than silently omitted or raising a `KeyError`.
    if (
        policy_tag.parent_policy_tag
        and policy_tag.parent_policy_tag in policy_tag_short_names
    ):
      hierarchy[policy_tag.parent_policy_tag].append(policy_tag)
    else:
      roots.append(policy_tag)

  assigned_short_names = set()
  dg_tag_value_actions = []
  bindings_map = {}
  policy_tag_display_paths = {}

  def assign_names_and_add_to_plan(
      current_policy_tag: analyzer.PolicyTagInfo,
      parent_namespaced_name: str,
      parent_path: list[str],
      parent_display_path: list[str],
  ) -> None:
    """Recursively assigns unique short names and emits Tag Value actions."""
    actual_short_name = policy_tag_short_names[current_policy_tag.name]

    current_display_path = parent_display_path + [
        current_policy_tag.display_name
    ]
    full_display_path = " > ".join(current_display_path)
    policy_tag_display_paths[current_policy_tag.name] = full_display_path

    # Ensure uniqueness of the Tag Value `short_name` across the entire taxonomy
    # using case-sensitive comparison (matching Resource Manager semantics).
    counter = 1
    original_short_name = actual_short_name
    while actual_short_name in assigned_short_names:
      actual_short_name = f"{original_short_name}-{counter}"
      counter += 1

    assigned_short_names.add(actual_short_name)
    policy_tag_short_names[current_policy_tag.name] = actual_short_name

    # Construct the full hierarchical namespaced path:
    # `<target_project_id>/<dg_tag_key_short_name>/<ancestor_1>/.../<leaf>`.
    current_path = parent_path + [actual_short_name]
    namespaced_value = "/".join(
        [target_project_id, dg_tag_key_short_name] + current_path
    )

    # Note on Deferred `parent` Resolution in Phase 2a:
    # `api_payload` intentionally omits the Resource Manager `parent` field
    # (`tagKeys/<id>` or `tagValues/<id>`) because numeric Tag Key/Value IDs are
    # assigned dynamically by GCP when the parent is created in Phase 2a.
    # Instead, we record `parent_namespaced_name` on the action dict, which
    # `Creator._get_parent_id` resolves dynamically at execution time.
    taxonomy_location = getattr(taxonomy, "location", "")
    primary_description = f"Migrated from Policy Tag: {full_display_path}"
    source_suffix = f"Source policy tag: {current_policy_tag.name}"
    full_lineage = f"{primary_description} | {source_suffix}"
    dg_tag_value_payload = {
        "short_name": actual_short_name,
        "description": primary_description[
            : constants.MAX_TAG_DESCRIPTION_LENGTH
        ],
    }

    dg_tag_value_warnings = _validate_short_name(actual_short_name)
    warnings_from_tag = getattr(current_policy_tag, "warnings", [])
    if warnings_from_tag:
      dg_tag_value_warnings.extend(warnings_from_tag)

    # Guardrail for Dangling IAM Bindings on Default-Allow Taxonomies:
    # When `taxonomy.is_access_control` is False (neither explicitly activated
    # with `FINE_GRAINED_ACCESS_CONTROL` nor implicitly activated by attached V1
    # Data Policies), BigQuery treats columns bound to this taxonomy as Default
    # Allow and ignores any `fineGrainedReader` bindings. Creating restrictive
    # V2 Data Policies for these tags would unexpectedly lock down columns and
    # break production queries; instead, we preserve Default Allow (zero V2 Data
    # Policies) and warn the customer about the inactive IAM bindings.
    if not taxonomy.is_access_control and (
        current_policy_tag.fine_grained_readers
        or getattr(taxonomy, "fine_grained_readers", [])
    ):
      dg_tag_value_warnings.append(
          "Inactive permissions found on this Policy Tag or Taxonomy. This"
          " Taxonomy has access control disabled, so these permissions are"
          " currently ignored by BigQuery. Migrating this setup to DGT without"
          " action will maintain unrestricted access, and these permissions"
          " will not be converted to Data Policies. Consider if this taxonomy"
          " should enforce access control. If yes, enable enforcement on the"
          " taxonomy and regenerate this plan."
      )

    dg_tag_value_action = {
        "namespaced_name": namespaced_value,
        "action": constants.ACTION_CREATE_DG_TAG_VALUE,
        "parent_namespaced_name": parent_namespaced_name,
        "api_payload": dg_tag_value_payload,
        "source_resource_name": current_policy_tag.name,
        "source_display_path": full_display_path,
        "source_taxonomy_name": taxonomy.name,
        "source_taxonomy_region": taxonomy_location,
        "audit_lineage": full_lineage,
    }
    if dg_tag_value_warnings:
      dg_tag_value_action["warnings"] = dg_tag_value_warnings

    dg_tag_value_actions.append(dg_tag_value_action)

    bindings_map[current_policy_tag.name] = {
        "dg_tag_key": f"{target_project_id}/{dg_tag_key_short_name}",
        "dg_tag_value": actual_short_name,
    }

    # Recursively visit child Policy Tags so parent actions always precede
    # child actions in `dg_tag_value_actions`.
    for child in hierarchy[current_policy_tag.name]:
      assign_names_and_add_to_plan(
          child, namespaced_value, current_path, current_display_path
      )

  for root in roots:
    assign_names_and_add_to_plan(
        root, namespaced_dg_tag_key, [], [taxonomy.display_name]
    )

  return (
      policy_tag_short_names,
      policy_tag_display_paths,
      dg_tag_value_actions,
      bindings_map,
  )


def _build_authorized_principal_dr_warning(
    converted_grantees: list[str],
) -> str | None:
  """Builds a `DR_WARN_04` warning for authorized view or dataset grantees.

  Why This Warning Exists (Delegation Gap & Cross-Region Replication Readiness):
  1. Unlike legacy Policy Tags, BigQuery Data Governance Tag policies do NOT
     delegate column-level access through Authorized Views or Authorized
     Datasets—querying users still receive `403 Access Denied` unless granted
     access directly in V2 Data Policy `grantees`.
  2. If retained in `grantees` and BigQuery Cross-Region Replication (DR) is
     enabled on the protected table, the dataset(s) containing those authorized
     views or datasets must also be replicated to the secondary region.

  Args:
      converted_grantees: List of IAM v3 principal URIs on the V2 Data Policy.

  Returns:
      Formatted `DR_WARN_04` warning string, or `None` if no authorized catalog
      principals are present.
  """
  authorized_catalog_principals = [
      grantee
      for grantee in converted_grantees
      if ("/datasets/" in grantee or "/views/" in grantee)
      and "/routines/" not in grantee
  ]
  if not authorized_catalog_principals:
    return None
  principals_str = ", ".join(authorized_catalog_principals)
  return (
      f"Warning [{constants.DR_WARN_04}]: This Data Policy grants access to"
      f" BigQuery authorized view or dataset principal(s) ({principals_str})."
      " BigQuery Data Governance Tag policies do not delegate column-level"
      " access through Authorized Views or Authorized Datasets—querying users"
      " still receive 403 Access Denied unless granted access directly in V2"
      " Data Policy grantees. In addition, if you plan to enable BigQuery"
      " Cross-Region Replication (Disaster Recovery), ensure the dataset(s)"
      " containing these authorized views or datasets are replicated to the"
      " secondary region."
  )


def _build_custom_routine_dr_warning(routine_path: str) -> str:
  """Builds a `DR_WARN_03` warning for a custom masking UDF routine.

  Why This Warning Exists (BigQuery Cross-Region Replication Readiness):
  When a `DATA_MASKING_POLICY` uses a custom BigQuery UDF masking routine
  (`projects/<project>/datasets/<dataset>/routines/<routine>`), BigQuery
  evaluates that routine in the region where the query runs. If the protected
  table is replicated to a DR secondary region without first replicating the
  dataset that owns the custom masking routine, queries on masked columns in the
  secondary region fail with `Access Denied`.

  Args:
      routine_path: Full V2 routine resource path
        (`projects/<p>/datasets/<d>/routines/<r>`).

  Returns:
      Formatted `DR_WARN_03` warning string reminding the customer to replicate
      the routine's parent dataset before enabling CRR.
  """
  routine_parts = routine_path.split("/")
  if (
      len(routine_parts) >= 4
      and routine_parts[0] == "projects"
      and routine_parts[2] == "datasets"
  ):
    routine_dataset = (
        f"{routine_parts[0]}/{routine_parts[1]}/"
        f"{routine_parts[2]}/{routine_parts[3]}"
    )
  else:
    routine_dataset = routine_path
  return (
      f"Warning [{constants.DR_WARN_03}]: This Data Policy references custom"
      f" masking routine '{routine_path}'. If you plan to enable BigQuery"
      " Cross-Region Replication (Disaster Recovery) on datasets protected by"
      " this policy after migration, you must first ensure the dataset"
      f" containing this routine ('{routine_dataset}') is also replicated to"
      " the secondary region; otherwise queries on masked columns in the"
      " secondary region will fail with Access Denied."
  )


def _map_data_policies(
    taxonomy: Any,
    policy_tag_short_names: dict[str, str],
    policy_tag_display_paths: dict[str, str],
    target_dgt_project_id: str,
    target_data_policy_project_ids: list[str],
    dg_tag_key_short_name: str,
    used_data_policy_ids_by_project: dict[tuple[str, str], set[str]],
    policy_tag_namespaced_values: dict[str, str] | None = None,
) -> tuple[list[dict[str, Any]], int, int]:
  """Synthesizes V2 Data Policy creation actions for all tags in a Taxonomy.

  Three-Tier V2 Data Policy Synthesis Architecture:
  -------------------------------------------------
  For every Policy Tag in `taxonomy.policy_tags`, this function generates V2
  Data Policy creation actions (`CREATE_DATA_POLICY_V2`) in `taxonomy.location`
  across every project in `target_data_policy_project_ids` (1 project in Mode 1
  `DEFAULT_DATA_POLICY_PROJECT`; N table parent projects in Mode 2
  `TABLE_PARENT_PROJECTS`), all referencing the shared global DG Tag Value in
  `target_dgt_project_id`:

  1. Policy 1 — Explicit Raw Reader Parity (`PARITY_RAW_READER`):
     - *When Created:* `taxonomy.is_access_control` is True and the Policy Tag
       has effective fine-grained readers.
     - *Taxonomy Reader Inheritance & Masked-Descendant Precedence:* In Data
       Catalog, granting `roles/datacatalog.categoryFineGrainedReader` on a
       Taxonomy resource grants unmasked read access directly at every Policy
       Tag in that taxonomy (overriding any child `DATA_MASKING_POLICY` if a
       principal holds both roles). In DGT V2, BigQuery selects the deepest Tag
       Value along the column's hierarchy that has a matching granted policy
       before applying `RAW`-over-`MASKED` tie-breaking. Therefore,
       `taxonomy.fine_grained_readers` are merged into **Root Tag Values**
       (`is_root_tag = True`) **and** into any non-root Tag Value that carries
       a direct `DATA_MASKING_POLICY` (`has_direct_masking_policy = True`).
       Unmasked descendant Tag Values inherit raw access via
       `column.matchTagHierarchy` without $O(V)$ policy duplication (even
       underneath a masked mid-level Tag Value, because both the masking policy
       and the taxonomy raw policy sit at that same mid-level depth).
     - *Naming:* `migrated_raw_<dg_tag_key>_<dg_tag_value>` (with `_1`, `_2`
       collision suffixes per `(project_id, location)`).
  2. Policy 2 — Fail-Closed Default Deny Seatbelt (`PARITY_DEFAULT_DENY`):
     - *When Created:* Created unconditionally for **every single Tag Value** in
       an access-controlled taxonomy (`taxonomy.is_access_control == True`),
       even if the tag or its root ancestor also has a Raw Reader or Masking
       policy.
     - *Why Mandatory (Defense-in-Depth Invariant):* Legacy Policy Tags are
       Fail-Closed by default, whereas Data Governance Tags without an attached
       V2 Data Policy are Fail-Open (Default Allow). Attaching a permanent
       `RAW_DATA_ACCESS_POLICY` with `grantees: []` (`_default_deny`) to every
       Tag Value guarantees that deleting or modifying a raw-reader or masking
       policy post-migration never causes columns to silently fall open to table
       readers.
     - *Naming:* `migrated_raw_<dg_tag_key>_<dg_tag_value>_default_deny`.
  3. Policy 3 — Migrated V1 Data Policies (`DATA_MASKING_POLICY` / `RAW`):
     - *When Created:* For every legacy V1 Data Policy attached to the Policy
       Tag (`policy_tag.data_policies`).
     - *Rule & Type Mapping:* Translates V1 `CUSTOM_ROUTINE_PREFIX` strings
       (`Custom Routine: <proj>.<ds>.<routine>`) into V2
       `projects/<proj>/datasets/<ds>/routines/<routine>` paths (using
       `rsplit(".", 2)`), maps predefined masking expressions
       to `predefined_expression`, and maps V1 `COLUMN_LEVEL_SECURITY_POLICY` /
       `RAW_DATA_ACCESS_POLICY` to V2 `RAW_DATA_ACCESS_POLICY`.

  Args:
      taxonomy: The `analyzer.TaxonomyInfo` object being mapped.
      policy_tag_short_names: Mapping of Policy Tag resource name to unique
        sanitized DG Tag Value `short_name`.
      policy_tag_display_paths: Mapping of Policy Tag resource name to full
        hierarchical display path (`<Taxonomy> > <Tag>`).
      target_dgt_project_id: Target GCP project ID owning the global DG Tags.
      target_data_policy_project_ids: List of target GCP project IDs where
        regional V2 Data Policies will be created.
      dg_tag_key_short_name: Sanitized `short_name` of the parent DG Tag Key.
      used_data_policy_ids_by_project: Mutable dict mapping
        `(data_policy_project_id, location)` to the set of `data_policy_id`s
        already allocated in that project and region.
      policy_tag_namespaced_values: Optional mapping of Policy Tag resource name
        to its full hierarchical DG Tag Value `namespaced_name`
        (`<project>/<key>/<parent_val>/<child_val>`).

  Returns:
      A 3-tuple `(data_policy_actions, target_data_policies_count,
      source_data_policies_count)`:
      - `data_policy_actions`: List of `CREATE_DATA_POLICY_V2` action dicts.
      - `target_data_policies_count`: Total number of V2 Data Policy actions
        generated across all target projects.
      - `source_data_policies_count`: Total number of source V1 Data Policies
        processed on this taxonomy.
  """
  data_policy_actions = []
  target_data_policies_count = 0
  source_data_policies_count = 0

  for policy_tag in taxonomy.policy_tags:
    tag_default_deny_actions: list[dict[str, Any]] = []
    policy_tag_short_name = policy_tag_short_names[policy_tag.name]
    dg_tag_value_namespaced_name = (
        policy_tag_namespaced_values.get(policy_tag.name)
        if policy_tag_namespaced_values
        else None
    ) or (
        f"{target_dgt_project_id}/"
        f"{dg_tag_key_short_name}/{policy_tag_short_name}"
    )
    if taxonomy.is_access_control:
      is_root_tag = (
          not policy_tag.parent_policy_tag
          or policy_tag.parent_policy_tag not in policy_tag_short_names
      )
      has_direct_masking_policy = any(
          data_policy_item.policy_type not in (
              constants.DATA_POLICY_TYPE_CLS,
              constants.DATA_POLICY_TYPE_RAW,
          )
          for data_policy_item in getattr(policy_tag, "data_policies", [])
      )
      # Merge taxonomy-level `fine_grained_readers` into Root Tag Values and
      # into any non-root Tag Value that has a direct masking policy. In DGT V2,
      # BigQuery resolves the deepest Tag Value with a granted policy before
      # breaking ties in favor of RAW over MASKED; copying taxonomy readers
      # onto masked non-root tags ensures principals holding both taxonomy-level
      # raw access and child-tag masked access continue to see unmasked data
      # (matching Policy Tag behavior), while unmasked child tags still inherit
      # via `matchTagHierarchy`.
      include_taxonomy_readers = bool(
          (is_root_tag or has_direct_masking_policy)
          and getattr(taxonomy, "fine_grained_readers", [])
      )
      if include_taxonomy_readers:
        effective_raw_readers = sorted(
            list(
                set(
                    policy_tag.fine_grained_readers
                    + taxonomy.fine_grained_readers
                )
            )
        )
      else:
        effective_raw_readers = sorted(
            list(set(policy_tag.fine_grained_readers))
        )

      # ------------------------------------------------------------------------
      # Policy 1: Explicit Raw Reader Parity (if effective raw readers exist)
      # ------------------------------------------------------------------------
      has_raw_readers = bool(effective_raw_readers)
      if has_raw_readers:
        base_raw_policy_id = sanitize_data_policy_id(
            f"{constants.PREFIX_MIGRATED_RAW_POLICY}"
            f"{dg_tag_key_short_name}_{policy_tag_short_name}"
        )
        tag_custom_roles = getattr(policy_tag, "custom_roles_by_principal", {})
        tax_custom_roles = (
            getattr(taxonomy, "custom_roles_by_principal", {})
            if include_taxonomy_readers
            else {}
        )
        custom_role_set: set[str] = set()
        for roles in tag_custom_roles.values():
          custom_role_set.update(roles)
        for roles in tax_custom_roles.values():
          custom_role_set.update(roles)
        matched_custom_roles = sorted(custom_role_set)
        custom_role_suffix = ""
        if matched_custom_roles:
          role_label = (
              "custom role"
              if len(matched_custom_roles) == 1
              else "custom roles"
          )
          custom_role_suffix = (
              f"; {role_label}: {', '.join(matched_custom_roles)}"
          )
        if include_taxonomy_readers:
          if policy_tag.fine_grained_readers:
            raw_lineage = (
                "Migrated from Policy Tag:"
                f" {policy_tag_display_paths[policy_tag.name]} and Taxonomy:"
                f" {taxonomy.display_name}"
                f" ({constants.PARITY_RAW_READER}{custom_role_suffix})"
            )
          else:
            raw_lineage = (
                f"Migrated from Taxonomy: {taxonomy.display_name}"
                f" ({constants.PARITY_RAW_READER}{custom_role_suffix})"
            )
        else:
          raw_lineage = (
              "Migrated from Policy Tag:"
              f" {policy_tag_display_paths[policy_tag.name]} ("
              f"{constants.PARITY_RAW_READER}{custom_role_suffix})"
          )

        converted_raw_grantees = [
            _convert_to_iam_v3_principal(grantee)
            for grantee in effective_raw_readers
        ]
        raw_grantee_warnings = _validate_grantees(
            converted_raw_grantees, policy_tag_display_paths[policy_tag.name]
        )
        raw_grantee_dr_warning = _build_authorized_principal_dr_warning(
            converted_raw_grantees
        )

        # Fan out an identical V2 Data Policy action into each target project
        # (`target_data_policy_project_ids`), resolving any per-(project,
        # region) ID collisions with underscore suffixes (`_1`, `_2`).
        for data_policy_project_id in target_data_policy_project_ids:
          target_data_policies_count += 1
          used_ids = used_data_policy_ids_by_project[
              (data_policy_project_id, taxonomy.location)
          ]
          raw_policy_id = base_raw_policy_id
          counter = 1
          while raw_policy_id in used_ids:
            raw_policy_id = f"{base_raw_policy_id}_{counter}"
            counter += 1
          used_ids.add(raw_policy_id)

          raw_data_policy_payload = {
              "data_policy_type": constants.DATA_POLICY_TYPE_RAW,
              "data_policy_id": raw_policy_id,
              "data_governance_tag": {
                  "key": f"{target_dgt_project_id}/{dg_tag_key_short_name}",
                  "value": policy_tag_short_name,
              },
              "grantees": list(converted_raw_grantees),
          }

          raw_data_policy_action = {
              "policy_id": raw_policy_id,
              "action": constants.ACTION_CREATE_DATA_POLICY_V2,
              "type": constants.DATA_POLICY_TYPE_RAW,
              "region": taxonomy.location,
              "target_project_id": data_policy_project_id,
              constants.FIELD_DG_TAG_VALUE_NAMESPACED_NAME: (
                  dg_tag_value_namespaced_name
              ),
              "api_payload": raw_data_policy_payload,
              "source_resource_name": policy_tag.name,
              "source_display_path": policy_tag_display_paths[policy_tag.name],
              "source_entity_type": constants.SOURCE_ENTITY_TYPE_POLICY_TAG,
              "note": constants.PARITY_RAW_READER,
              "audit_lineage": raw_lineage,
          }
          raw_policy_warnings = _validate_data_policy_id(raw_policy_id)
          warnings_from_tag = getattr(policy_tag, "warnings", [])
          if warnings_from_tag:
            raw_policy_warnings.extend(warnings_from_tag)
          # Propagate taxonomy-level IAM/custom-role warnings to the Root Tag
          # Value's Raw Reader policy so they appear once per root without
          # being duplicated on the root's Default Deny policy below.
          if is_root_tag:
            for warning in getattr(taxonomy, "warnings", []):
              if warning not in raw_policy_warnings:
                raw_policy_warnings.append(warning)
          if raw_grantee_warnings:
            raw_policy_warnings.extend(raw_grantee_warnings)
          if raw_grantee_dr_warning:
            raw_policy_warnings.append(raw_grantee_dr_warning)
          if raw_policy_warnings:
            raw_data_policy_action["warnings"] = raw_policy_warnings
          data_policy_actions.append(raw_data_policy_action)

      # ------------------------------------------------------------------------
      # Policy 2: Fail-Closed Default Deny Safety Net (Every Single Tag Value)
      # ------------------------------------------------------------------------
      # SECURITY INVARIANT (DO NOT REMOVE OR BYPASS):
      # Every single Tag Value in an access-controlled taxonomy MUST receive a
      # `RAW_DATA_ACCESS_POLICY` with empty `grantees: []` (`_default_deny`).
      # Legacy Policy Tags are Fail-Closed by default: attaching an
      # access-controlled policy tag to a column denies everyone unless
      # explicitly granted. Data Governance Tags are Fail-Open: a tag without an
      # attached data policy permits raw table access. If a parent/ancestor or
      # direct raw data policy is ever deleted later, a tag lacking its own
      # default-deny policy would silently become Fail-Open, creating an
      # unintended data exposure. Creating a `_default_deny` policy for every
      # tag value ensures an immutable defense-in-depth safety net across the
      # entire lifecycle of the tag.
      base_deny_policy_id = sanitize_data_policy_id(
          f"{constants.PREFIX_MIGRATED_RAW_POLICY}"
          f"{dg_tag_key_short_name}_{policy_tag_short_name}"
          f"{constants.SUFFIX_DEFAULT_DENY_POLICY}"
      )
      for data_policy_project_id in target_data_policy_project_ids:
        target_data_policies_count += 1
        used_ids = used_data_policy_ids_by_project[
            (data_policy_project_id, taxonomy.location)
        ]
        deny_policy_id = base_deny_policy_id
        counter = 1
        while deny_policy_id in used_ids:
          deny_policy_id = f"{base_deny_policy_id}_{counter}"
          counter += 1
        used_ids.add(deny_policy_id)

        deny_data_policy_payload = {
            "data_policy_type": constants.DATA_POLICY_TYPE_RAW,
            "data_policy_id": deny_policy_id,
            "data_governance_tag": {
                "key": f"{target_dgt_project_id}/{dg_tag_key_short_name}",
                "value": policy_tag_short_name,
            },
            "grantees": [],
        }

        deny_data_policy_action = {
            "policy_id": deny_policy_id,
            "action": constants.ACTION_CREATE_DATA_POLICY_V2,
            "type": constants.DATA_POLICY_TYPE_RAW,
            "region": taxonomy.location,
            "target_project_id": data_policy_project_id,
            constants.FIELD_DG_TAG_VALUE_NAMESPACED_NAME: (
                dg_tag_value_namespaced_name
            ),
            "api_payload": deny_data_policy_payload,
            "source_resource_name": policy_tag.name,
            "source_display_path": policy_tag_display_paths[policy_tag.name],
            "source_entity_type": constants.SOURCE_ENTITY_TYPE_POLICY_TAG,
            "note": constants.PARITY_DEFAULT_DENY,
            "audit_lineage": (
                "Migrated from Policy Tag:"
                f" {policy_tag_display_paths[policy_tag.name]} ("
                f"{constants.PARITY_DEFAULT_DENY})"
            ),
        }
        deny_policy_warnings = _validate_data_policy_id(deny_policy_id)
        warnings_from_tag = getattr(policy_tag, "warnings", [])
        if warnings_from_tag:
          deny_policy_warnings.extend(warnings_from_tag)
        # If the Root Tag Value had no effective raw readers (so no Policy 1
        # action was emitted above), attach any taxonomy-level IAM warnings to
        # the root's Default Deny policy so they are never lost.
        if is_root_tag and not has_raw_readers:
          for warning in getattr(taxonomy, "warnings", []):
            if warning not in deny_policy_warnings:
              deny_policy_warnings.append(warning)
        if deny_policy_warnings:
          deny_data_policy_action["warnings"] = deny_policy_warnings
        tag_default_deny_actions.append(deny_data_policy_action)
        data_policy_actions.append(deny_data_policy_action)

    # --------------------------------------------------------------------------
    # Policy 3: Migrated V1 Data Policies (Masking & Raw/CLS Policies)
    # --------------------------------------------------------------------------
    # BigQuery Data Policy Service V2 supports binding multiple
    # `DATA_MASKING_POLICY` resources to the same DG Tag Value. At query time,
    # if a user matches multiple predefined masking policies at the winning tag
    # depth without matching a `RAW_DATA_ACCESS_POLICY`, BigQuery selects the
    # effective policy deterministically by restrictiveness score. However, if a
    # user matches two or more custom masking routine (`routine`) policies at
    # the same tag depth without raw access, BigQuery fails closed with
    # `Found multiple conflicting data policies with custom masking
    # expressions.`
    direct_raw_grantees_on_tag: set[str] = set()
    if taxonomy.is_access_control:
      for raw_reader in effective_raw_readers:
        direct_raw_grantees_on_tag.add(_convert_to_iam_v3_principal(raw_reader))
    for candidate_policy in policy_tag.data_policies:
      if candidate_policy.policy_type in (
          constants.DATA_POLICY_TYPE_CLS,
          constants.DATA_POLICY_TYPE_RAW,
      ):
        for raw_reader in candidate_policy.raw_readers:
          direct_raw_grantees_on_tag.add(
              _convert_to_iam_v3_principal(raw_reader)
          )

    custom_routine_policies_on_tag = [
        candidate_policy
        for candidate_policy in policy_tag.data_policies
        if candidate_policy.policy_type not in (
            constants.DATA_POLICY_TYPE_CLS,
            constants.DATA_POLICY_TYPE_RAW,
        )
        and (candidate_policy.masking_rule or "").startswith(
            constants.CUSTOM_ROUTINE_PREFIX
        )
    ]
    custom_routine_grantee_counts: dict[str, int] = collections.defaultdict(int)
    for custom_policy in custom_routine_policies_on_tag:
      for custom_grantee in {
          _convert_to_iam_v3_principal(masked_reader)
          for masked_reader in custom_policy.masked_readers
      }:
        if custom_grantee not in direct_raw_grantees_on_tag:
          custom_routine_grantee_counts[custom_grantee] += 1
    overlapping_custom_routine_grantees = sorted(
        grantee_uri
        for grantee_uri, count in custom_routine_grantee_counts.items()
        if count > 1
    )

    source_data_policies_count += len(policy_tag.data_policies)
    for data_policy in policy_tag.data_policies:
      # Extract the V1 Data Policy short ID (last path segment) from
      # `projects/<project>/locations/<location>/dataPolicies/<policy_id>`.
      data_policy_name_short = data_policy.name.split("/")[-1]
      masking_policy = {}
      if data_policy.masking_rule:
        if data_policy.masking_rule.startswith(constants.CUSTOM_ROUTINE_PREFIX):
          routine_dot_notation = data_policy.masking_rule.replace(
              constants.CUSTOM_ROUTINE_PREFIX, ""
          ).strip()
          # Convert `<project_id>.<dataset_id>.<routine_id>` into the V2 API's
          # full resource path `projects/<p>/datasets/<d>/routines/<r>`.
          parts = routine_dot_notation.rsplit(".", 2)
          if len(parts) == 3:
            masking_policy["routine"] = (
                f"projects/{parts[0]}/datasets/{parts[1]}/routines/{parts[2]}"
            )
          else:
            masking_policy["routine"] = routine_dot_notation
        else:
          masking_policy["predefined_expression"] = data_policy.masking_rule

      policy_tag_short_name = policy_tag_short_names[policy_tag.name]

      # Map V1 `COLUMN_LEVEL_SECURITY_POLICY` and `RAW_DATA_ACCESS_POLICY` to
      # V2 `RAW_DATA_ACCESS_POLICY` (`migrated_raw_`), and V1
      # `DATA_MASKING_POLICY` to V2 `DATA_MASKING_POLICY` (`migrated_masking_`).
      policy_type = data_policy.policy_type
      if policy_type in [
          constants.DATA_POLICY_TYPE_CLS,
          constants.DATA_POLICY_TYPE_RAW,
      ]:
        data_policy_type = constants.DATA_POLICY_TYPE_RAW
        grantees = data_policy.raw_readers
        prefix = constants.PREFIX_MIGRATED_RAW_POLICY
      else:
        data_policy_type = constants.DATA_POLICY_TYPE_MASKING
        grantees = data_policy.masked_readers
        prefix = constants.PREFIX_MIGRATED_MASKING_POLICY

      base_policy_id = sanitize_data_policy_id(
          f"{prefix}{dg_tag_key_short_name}_{data_policy_name_short}"
      )
      converted_grantees = [
          _convert_to_iam_v3_principal(grantee) for grantee in grantees
      ]
      grantee_validation_warnings = _validate_grantees(
          converted_grantees, data_policy_name_short
      )
      grantee_dr_warning = _build_authorized_principal_dr_warning(
          converted_grantees
      )
      routine_dr_warning = (
          _build_custom_routine_dr_warning(masking_policy["routine"])
          if "routine" in masking_policy
          else None
      )

      # Skip redundant empty V2 RAW_DATA_ACCESS_POLICY actions for legacy V1
      # `COLUMN_LEVEL_SECURITY_POLICY` markers with zero raw readers: Policy 2
      # (`_default_deny`, `grantees: []`) already enforces fail-closed parity
      # on every Tag Value in an access-controlled taxonomy without burning a
      # second slot against the 1,000-policy-per-Tag-Key quota. Forward any
      # `[ACTION REQUIRED]` warnings captured on the source V1 policy (such as
      # omitted conditional IAM bindings or failed custom role lookups) onto
      # the tag's `_default_deny` policy actions so they are never silently
      # dropped.
      if (
          policy_type == constants.DATA_POLICY_TYPE_CLS
          and not converted_grantees
          and taxonomy.is_access_control
      ):
        warnings_from_skipped_policy = getattr(data_policy, "warnings", [])
        if warnings_from_skipped_policy:
          for deny_action in tag_default_deny_actions:
            deny_warnings = deny_action.setdefault("warnings", [])
            for warning in warnings_from_skipped_policy:
              if warning not in deny_warnings:
                deny_warnings.append(warning)
        continue

      for data_policy_project_id in target_data_policy_project_ids:
        target_data_policies_count += 1
        used_ids = used_data_policy_ids_by_project[
            (data_policy_project_id, taxonomy.location)
        ]
        policy_id = base_policy_id
        counter = 1
        while policy_id in used_ids:
          policy_id = f"{base_policy_id}_{counter}"
          counter += 1
        used_ids.add(policy_id)

        data_policy_payload: dict[str, Any] = {
            "data_policy_type": data_policy_type,
            "data_policy_id": policy_id,
            # Bind the V2 Data Policy directly to the migrated global Data
            # Governance Tag Key and Tag Value short name.
            "data_governance_tag": {
                "key": f"{target_dgt_project_id}/{dg_tag_key_short_name}",
                "value": policy_tag_short_name,
            },
            "grantees": list(converted_grantees),
        }

        if data_policy_type == constants.DATA_POLICY_TYPE_MASKING:
          data_policy_payload["data_masking_policy"] = dict(masking_policy)

        data_policy_action = {
            "policy_id": policy_id,
            "action": constants.ACTION_CREATE_DATA_POLICY_V2,
            "type": data_policy_type,
            "region": taxonomy.location,
            "target_project_id": data_policy_project_id,
            constants.FIELD_DG_TAG_VALUE_NAMESPACED_NAME: (
                dg_tag_value_namespaced_name
            ),
            "api_payload": data_policy_payload,
            "source_resource_name": data_policy.name,
            "source_display_path": (
                f"{policy_tag_display_paths[policy_tag.name]} >"
                f" {data_policy_name_short}"
            ),
            "source_entity_type": data_policy.policy_type,
            "audit_lineage": (
                "Migrated from Data Policy:"
                f" {policy_tag_display_paths[policy_tag.name]} >"
                f" {data_policy_name_short}"
                f" ({data_policy.policy_type})"
            ),
        }
        data_policy_warnings = _validate_data_policy_id(policy_id)
        warnings_from_policy = getattr(data_policy, "warnings", [])
        if warnings_from_policy:
          data_policy_warnings.extend(warnings_from_policy)
        if policy_type == constants.DATA_POLICY_TYPE_CLS and converted_grantees:
          data_policy_warnings.append(
              "Source V1 policy has type COLUMN_LEVEL_SECURITY_POLICY with raw"
              f" reader bindings ({', '.join(converted_grantees)}). Legacy V1"
              " ignored rawDataReader on COLUMN_LEVEL_SECURITY_POLICY, whereas"
              " V2 RAW_DATA_ACCESS_POLICY grants unmasked access. [ACTION"
              " REQUIRED: Verify these principals should receive unmasked"
              " access or clear 'grantees' in plan.json before '--phase"
              " create'.]"
          )
        # BigQuery Data Policy Service V2 rejects `DATA_MASKING_POLICY` payloads
        # with an empty `data_masking_policy: {}` (`INVALID_ARGUMENT`). Emit an
        # explicit `[ACTION REQUIRED]` warning when the source V1 masking policy
        # has neither a predefined expression nor a custom routine so both
        # `--phase create` (including `--dry-run`) and forward `--phase swap`
        # block upfront until resolved.
        if (
            data_policy_type == constants.DATA_POLICY_TYPE_MASKING
            and not masking_policy.get("predefined_expression")
            and not masking_policy.get("routine")
        ):
          data_policy_warnings.append(
              f"Source V1 DATA_MASKING_POLICY '{data_policy.name}' has no"
              " masking expression or custom routine"
              " ('api_payload.data_masking_policy' is empty). BigQuery Data"
              " Policy Service V2 requires an explicit 'predefined_expression'"
              " or 'routine' on every DATA_MASKING_POLICY. [ACTION REQUIRED:"
              " Populate 'api_payload.data_masking_policy' with a valid"
              " 'predefined_expression' or 'routine' (or remove this Data"
              " Policy entry) in the migration plan before running '--phase"
              " create'.]"
          )
        # If `Analyzer` could not resolve a custom routine's numeric project
        # number to a project ID (inserting `<unknown-project-...>`), surface
        # an explicit `[ACTION REQUIRED]` warning so the operator replaces the
        # placeholder before Phase 2a creation.
        routine_path = masking_policy.get("routine", "")
        if "<unknown-project-" in routine_path:
          data_policy_warnings.append(
              f"Custom masking routine '{routine_path}' contains"
              " an unresolved project number placeholder. [ACTION REQUIRED:"
              " Replace '<unknown-project-...>' with the actual routine"
              " project ID in the migration plan before running '--phase"
              " create'.]"
          )
        elif routine_path:
          # BigQuery Data Policy Service V2 enforces that
          # `data_masking_policy.routine` resides in the exact same GCP project
          # as the V2 Data Policy (`All referenced resources must reside in the
          # same project.`). Flag cross-project custom routine references in
          # Mode 1 (when `--target-default-dp-project-id` differs from the
          # routine project) and Mode 2 (`--target-table-dp-project-ids` fan-out
          # to secondary table projects).
          routine_parts = routine_path.split("/")
          routine_project_id = ""
          if (
              len(routine_parts) == 6
              and routine_parts[0] == "projects"
              and routine_parts[2] == "datasets"
              and routine_parts[4] == "routines"
          ):
            routine_project_id = routine_parts[1]
          if (
              routine_project_id
              and data_policy_project_id
              and routine_project_id != data_policy_project_id
          ):
            data_policy_warnings.append(
                f"Custom masking routine '{routine_path}' resides in project"
                f" '{routine_project_id}', which differs from target Data"
                f" Policy project '{data_policy_project_id}'. BigQuery Data"
                " Policy Service requires custom masking routines to reside in"
                " the same project as the Data Policy ('All referenced"
                " resources must reside in the same project.'). [ACTION"
                " REQUIRED: Create an equivalent DATA_MASKING routine in"
                f" project '{data_policy_project_id}' and update"
                " 'api_payload.data_masking_policy.routine' in the migration"
                " plan (or remove this Data Policy entry if no tables in"
                f" '{data_policy_project_id}' use this tag) before running"
                " '--phase create'.]"
            )
        if grantee_validation_warnings:
          data_policy_warnings.extend(grantee_validation_warnings)
        if (
            data_policy_type == constants.DATA_POLICY_TYPE_MASKING
            and "routine" in masking_policy
            and len(custom_routine_policies_on_tag) > 1
        ):
          policy_overlapping_grantees = [
              grantee_uri
              for grantee_uri in overlapping_custom_routine_grantees
              if grantee_uri in converted_grantees
          ]
          if policy_overlapping_grantees:
            overlap_str = ", ".join(policy_overlapping_grantees)
            data_policy_warnings.append(
                "Multiple custom masking routine policies on Tag Value"
                f" '{dg_tag_value_namespaced_name}' grant masked access to the"
                f" same principal(s) ({overlap_str}) without direct raw data"
                " access. BigQuery fails closed at query time ('Found multiple"
                " conflicting data policies with custom masking expressions.')"
                " when a user matches multiple custom masking routine policies"
                " at the same tag depth. [ACTION REQUIRED: Consolidate"
                " custom masking routine policies or make their grantees"
                " mutually exclusive before running '--phase create'.]"
            )
          else:
            data_policy_warnings.append(
                "Warning: Multiple custom masking routine policies target Tag"
                f" Value '{dg_tag_value_namespaced_name}'. Ensure group"
                " memberships across sibling custom masking routine policies"
                " do not overlap (unless overlapping users also hold"
                " RAW_DATA_ACCESS_POLICY on this tag), or BigQuery queries"
                " will fail with a conflicting custom masking policy error."
            )
        if routine_dr_warning:
          data_policy_warnings.append(routine_dr_warning)
        if grantee_dr_warning:
          data_policy_warnings.append(grantee_dr_warning)
        if data_policy_warnings:
          data_policy_action["warnings"] = data_policy_warnings
        data_policy_actions.append(data_policy_action)

  return (
      data_policy_actions,
      target_data_policies_count,
      source_data_policies_count,
  )


# ==============================================================================
# Section 3: Migration Planner Facade (`Planner`)
# ==============================================================================


class Planner:
  """Orchestrates Phase 1b migration plan generation and Markdown reporting.

  Responsibilities:
  1. `generate_plan`: Validates single-source-project and target-project inputs,
     maps regional taxonomies to global DG Tag Keys/Values and regional V2 Data
     Policies, enforces the 1,000-policy per-(project, tag_key) service limit,
     and runs `validate_plan_dr_readiness`.
  2. `validate_plan_dr_readiness`: Audits `phase_2_resource_manifest` for
     multi-region V2 Data Policy conflicts on the same DG Tag Key
     (`DR_WARN_01`).
  3. `generate_markdown_report`: Renders the human-readable Markdown plan
     summary with target architecture guidance (`DR_WARN_02`), Separation-Only
     rationale, source/target metrics, five entity mapping tables, and
     collected warnings.
  """

  def __init__(self, tool_version: str = "1.0.0"):
    """Initializes `Planner` with the tool version recorded in `metadata`."""
    self.tool_version = tool_version

  def validate_plan_dr_readiness(self, plan: dict[str, Any]) -> list[str]:
    """Audits `plan` for multi-region V2 Data Policy conflicts (`DR_WARN_01`).

    Why This Check Exists (Defensive Guardrail for Manual `plan.json` Edits):
    By default, `_map_taxonomy_to_dg_tag_key` uses a Separation-Only (1:1)
    mapping so each regional taxonomy receives its own distinct global DG Tag
    Key and never has V2 Data Policies across multiple regions. However, if a
    customer manually edits `plan.json` to consolidate multi-region V2 Data
    Policies onto a single shared DG Tag Key within the same target project,
    pre-creating standalone V2 Data Policies in both primary and secondary
    regions will cause BigQuery Cross-Region Replication (DR) dataset
    replication to fail in the secondary region. This method detects that
    condition and attaches `DR_WARN_01` to the corresponding DG Tag Key action.

    Args:
        plan: The migration plan dictionary (`plan.json` structure).

    Returns:
        List of `DR_WARN_01` warning strings detected and attached to the plan.
    """
    manifest = plan.get(constants.KEY_PHASE_2_RESOURCE_MANIFEST, {})
    policy_sections = [
        constants.KEY_POLICY_TAGS_TO_RAW_READER_DATA_POLICIES_V2,
        constants.KEY_POLICY_TAGS_TO_DEFAULT_DENY_DATA_POLICIES_V2,
        constants.KEY_DATA_POLICIES_V1_TO_DATA_POLICIES_V2,
    ]
    regions_by_project_and_key: dict[tuple[str, str], set[str]] = (
        collections.defaultdict(set)
    )
    for section_key in policy_sections:
      for action in manifest.get(section_key, []):
        if action.get("action") != constants.ACTION_CREATE_DATA_POLICY_V2:
          continue
        region = action.get(constants.FIELD_REGION, "")
        target_project = action.get(constants.FIELD_TARGET_PROJECT_ID, "")
        payload = action.get(constants.FIELD_API_PAYLOAD, {})
        dg_tag_key = payload.get("data_governance_tag", {}).get("key", "")
        if region and dg_tag_key:
          regions_by_project_and_key[(target_project, dg_tag_key)].add(region)

    tag_key_actions_by_name = {
        action.get(constants.FIELD_NAMESPACED_NAME): action
        for action in manifest.get(constants.KEY_TAXONOMIES_TO_DG_TAG_KEYS, [])
    }

    dr_warnings = []
    for (
        target_project,
        dg_tag_key,
    ), regions in sorted(regions_by_project_and_key.items()):
      if len(regions) > 1:
        regions_str = ", ".join(sorted(regions))
        warning_message = (
            f"Warning [{constants.DR_WARN_01}]: Data Governance Tag Key"
            f" '{dg_tag_key}' has Data Policies scheduled for creation in"
            f" multiple regions ({regions_str}) in project '{target_project}'."
            " If you plan to use BigQuery Cross-Region Replication (Disaster"
            " Recovery) for datasets using this tag key, pre-creating"
            " standalone Data Policies for the same tag key in both primary"
            " and secondary regions will cause dataset replication to fail due"
            " to a policy conflict in the secondary region. To support"
            " Disaster Recovery, either keep separate Tag Keys per source"
            " region (default) or only create Data Policies in your primary"
            " region and allow BigQuery Cross-Region Replication to"
            " automatically replicate those policies to the secondary region."
        )
        dr_warnings.append(warning_message)
        tag_key_action = tag_key_actions_by_name.get(dg_tag_key)
        if tag_key_action is not None:
          existing_warnings = tag_key_action.setdefault("warnings", [])
          if warning_message not in existing_warnings:
            existing_warnings.append(warning_message)

    return dr_warnings

  def generate_plan(
      self,
      analysis_results: list[analyzer.StaticTaxonomyAnalysisResult],
      target_dgt_project_id: str,
      target_data_policy_project_ids: list[str],
      target_data_policy_mode: str = (
          constants.TARGET_DATA_POLICY_MODE_DEFAULT_PROJECT
      ),
      collision_resolution: str = constants.COLLISION_RESOLUTION_COUNTER,
      space_replacement: str = "_",
      collapse_spaces: bool = True,
  ) -> dict[str, Any]:
    """Generates the complete Phase 1b migration plan (`plan.json` dictionary).

    Step-by-Step Execution Flow:
    1. Input & Single-Source-Project Validation:
       Verifies `target_dgt_project_id`, `target_data_policy_project_ids`,
       `collision_resolution`, and confirms all non-error `analysis_results`
       belong to a single `source_project_id`.
    2. Cross-Region Collision Pre-Scan:
       Counts sanitized taxonomy base names across all scanned regions so
       `--collision-resolution from_region` can symmetrically append
       `_from_<region>` to every colliding taxonomy.
    3. Taxonomy, Policy Tag & V2 Data Policy Mapping:
       For each region and taxonomy, invokes `_map_taxonomy_to_dg_tag_key`,
       `_map_policy_tags_to_dg_tag_values`, and `_map_data_policies`,
       populating `phase_2_resource_manifest` and `phase_3_binding_map`.
    4. Per-Tag-Key Service Quota Check (`MAX_DATA_POLICIES_PER_DG_TAG_KEY`):
       Tracks cumulative V2 Data Policy counts per `(target_project_id,`
       `namespaced_dg_tag_key)` and attaches `[ACTION REQUIRED]` warnings to
       both the DG Tag Key action and any individual policy action at index
       `>= 1000`.
    5. Summary Metrics & DR Readiness Validation:
       Populates `plan_summary` (`source_metrics` and `target_metrics`) and
       executes `validate_plan_dr_readiness(plan)`.

    Args:
        analysis_results: Regional discovery results from
          `Analyzer.analyze_static_taxonomies()`.
        target_dgt_project_id: Single target GCP project ID where global DG Tag
          Keys and Tag Values will be created (required).
        target_data_policy_project_ids: One or more target GCP project IDs where
          regional V2 Data Policies will be created (required).
        target_data_policy_mode: Placement mode for V2 Data Policies
          (`DEFAULT_DATA_POLICY_PROJECT` Mode 1 or `TABLE_PARENT_PROJECTS` Mode
          2).
        collision_resolution: Strategy for resolving Tag Key `short_name`
          collisions (`"counter"` or `"from_region"`).
        space_replacement: Replacement string for spaces in names (default:
          `"_"`).
        collapse_spaces: Whether to collapse consecutive spaces in names.

    Returns:
        Dictionary representing the complete `plan.json` migration plan.

    Raises:
        ValueError: If `target_dgt_project_id` or
          `target_data_policy_project_ids` is empty, if `collision_resolution`
          is unsupported, or if `analysis_results` spans multiple source
          projects.
    """
    # ==========================================================================
    # Step 1: Validate Target Project Architecture & Single Source Project
    # ==========================================================================
    if not target_dgt_project_id or not target_dgt_project_id.strip():
      raise ValueError("target_dgt_project_id is required.")
    target_dgt_project_id = constants.validate_standard_project_id(
        target_dgt_project_id, "target_dgt_project_id"
    )

    normalized_data_policy_projects = [
        constants.validate_standard_project_id(
            project, "target_data_policy_project_ids"
        )
        for project in target_data_policy_project_ids or []
        if project and project.strip()
    ]
    if not normalized_data_policy_projects:
      raise ValueError(
          "At least one target Data Policy project ID is required in"
          " target_data_policy_project_ids."
      )

    if collision_resolution not in (
        constants.COLLISION_RESOLUTION_COUNTER,
        constants.COLLISION_RESOLUTION_FROM_REGION,
    ):
      raise ValueError(
          f"Unsupported collision_resolution: {collision_resolution}"
      )

    for result in analysis_results:
      if result.project_id:
        constants.validate_standard_project_id(
            result.project_id, "source_project_id"
        )

    valid_source_projects = []
    for result in analysis_results:
      if not result.error and result.project_id:
        if result.project_id not in valid_source_projects:
          valid_source_projects.append(result.project_id)
    if len(valid_source_projects) > 1:
      raise ValueError(
          "Only a single source project is supported per migration plan, but"
          f" found multiple source projects: {valid_source_projects}"
      )
    source_project_id = (
        valid_source_projects[0]
        if valid_source_projects
        else (analysis_results[0].project_id if analysis_results else "")
    )

    # ==========================================================================
    # Step 2: Initialize `plan.json` Skeleton & Pre-Scan Taxonomy Collisions
    # ==========================================================================
    plan = {
        "metadata": {
            constants.FIELD_SCHEMA_VERSION: constants.PLAN_SCHEMA_VERSION,
            "source_project_id": source_project_id,
            "target_dgt_project_id": target_dgt_project_id,
            "target_data_policy_mode": target_data_policy_mode,
            "target_data_policy_project_ids": list(
                normalized_data_policy_projects
            ),
            "collision_resolution": collision_resolution,
            "source_regions": [],
            "generation_timestamp": (
                datetime.datetime.now(datetime.timezone.utc).isoformat()
            ),
            "tool_version": self.tool_version,
            "description": (
                "Migration plan from Policy Tags to Data Governance Tags"
            ),
        },
        "plan_summary": {
            "total_taxonomies_mapped": 0,
            "total_tags_to_create": 0,
            "total_policies_to_create": 0,
            # Currently only PROJECT_LEVEL scope (`projects/<id>`) is used for
            # target DG Tag Keys.
            "scope": "PROJECT_LEVEL",
            "source_metrics": {
                "total_taxonomies": 0,
                "total_policy_tags": 0,
                "total_data_policies": 0,
            },
            "target_metrics": {
                "total_tag_keys": 0,
                "total_tag_values": 0,
                "total_data_policies": 0,
            },
        },
        # Phase 2a/2b Resource Manifest: 5 ordered lists of creation actions.
        "phase_2_resource_manifest": {
            "comment": (
                "Resource manifest for Phase 2. Contains lists of creation"
                " actions for Tag Keys, Tag Values, and Data Policies."
            ),
            constants.KEY_TAXONOMIES_TO_DG_TAG_KEYS: [],
            constants.KEY_POLICY_TAGS_TO_DG_TAG_VALUES: [],
            constants.KEY_POLICY_TAGS_TO_RAW_READER_DATA_POLICIES_V2: [],
            constants.KEY_POLICY_TAGS_TO_DEFAULT_DENY_DATA_POLICIES_V2: [],
            constants.KEY_DATA_POLICIES_V1_TO_DATA_POLICIES_V2: [],
        },
        # Phase 3 Binding Map: forward (`pt-to-dgt`) and reverse (`dgt-to-pt`
        # rollback) lookup table mapping source Policy Tag resource names to
        # target DG Tag Key/Value short names.
        "phase_3_binding_map": {
            "comment": (
                "Lookup table for Phase 3. Keys are Policy Tag Resource Names;"
                " Values are Target DGT Identifiers."
            ),
            constants.KEY_POLICY_TAGS_TO_DG_TAG_VALUES: {},
        },
    }

    # Pre-scan sanitized taxonomy display names across all regions so
    # `--collision-resolution from_region` knows up front which base names
    # appear more than once and can suffix both the first and subsequent keys.
    base_name_counts: dict[str, int] = collections.Counter()
    for result in analysis_results:
      if result.error:
        continue
      for taxonomy in result.taxonomies:
        sanitized_base = sanitize_name(
            taxonomy.display_name,
            space_replacement=space_replacement,
            collapse_spaces=collapse_spaces,
        )
        base_name_counts[sanitized_base] += 1
    colliding_base_names = {
        name for name, count in base_name_counts.items() if count > 1
    }

    # ==========================================================================
    # Step 3: Map Each Regional Taxonomy to DG Tag Keys, Values & V2 Policies
    # ==========================================================================
    source_taxonomies = 0
    source_policy_tags = 0
    source_data_policies = 0

    target_dg_tag_keys = 0
    target_dg_tag_values = 0
    target_data_policies = 0

    used_dg_tag_keys: set[str] = set()
    used_data_policy_ids_by_project: dict[tuple[str, str], set[str]] = (
        collections.defaultdict(set)
    )
    data_policies_count_by_project_and_tag_key: dict[tuple[str, str], int] = (
        collections.defaultdict(int)
    )

    for result in analysis_results:
      if result.error:
        cleaned_error = str(result.error).rstrip(".")
        error_warning = (
            "[CRITICAL] Static taxonomy analysis failed in region"
            f" '{result.location}': {cleaned_error}. Taxonomies and policies"
            f" from region '{result.location}' are omitted from this migration"
            " plan. [ACTION REQUIRED: Resolve the error and re-run '--phase"
            " plan' before proceeding.]"
        )
        plan.setdefault("warnings", []).append(error_warning)
        continue
      taxonomies = result.taxonomies
      source_regions = cast(list[str], plan["metadata"]["source_regions"])

      if result.location not in source_regions:
        source_regions.append(result.location)

      for taxonomy in taxonomies:
        source_taxonomies += 1
        source_policy_tags += len(taxonomy.policy_tags)
        target_dg_tag_keys += 1  # Separation-Only 1:1 taxonomy-to-key mapping

        # Step 3a: Map Taxonomy to global DG Tag Key.
        dg_tag_key_short_name, namespaced_dg_tag_key, dg_tag_key_action = (
            _map_taxonomy_to_dg_tag_key(
                taxonomy,
                target_dgt_project_id,
                space_replacement,
                collapse_spaces,
                used_dg_tag_keys,
                collision_resolution=collision_resolution,
                colliding_base_names=colliding_base_names,
            )
        )
        if target_dg_tag_keys > constants.MAX_DG_TAG_KEYS_PER_PROJECT:
          dg_tag_key_action.setdefault("warnings", []).append(
              f"Target project '{target_dgt_project_id}' exceeds the Google"
              " Cloud Resource Manager limit of"
              f" {constants.MAX_DG_TAG_KEYS_PER_PROJECT} Tag Keys per project"
              f" (at Tag Key #{target_dg_tag_keys}: '{namespaced_dg_tag_key}')."
              " [ACTION REQUIRED: Distribute taxonomies across multiple"
              " '--target-dgt-project-id' projects or prune unused taxonomies"
              " before running '--phase create'.]"
          )
        cast(
            list[Any],
            plan["phase_2_resource_manifest"][
                constants.KEY_TAXONOMIES_TO_DG_TAG_KEYS
            ],
        ).append(dg_tag_key_action)

        # Step 3b: Map Policy Tags to hierarchical DG Tag Values and Phase 3
        # binding map entries.
        (
            policy_tag_short_names,
            policy_tag_display_paths,
            dg_tag_value_actions,
            bindings_map,
        ) = _map_policy_tags_to_dg_tag_values(
            taxonomy,
            target_dgt_project_id,
            dg_tag_key_short_name,
            namespaced_dg_tag_key,
            space_replacement,
            collapse_spaces,
        )
        target_dg_tag_values += len(taxonomy.policy_tags)
        if len(dg_tag_value_actions) > constants.MAX_DG_TAG_VALUES_PER_TAG_KEY:
          dg_tag_key_action.setdefault("warnings", []).append(
              f"DG Tag Key '{namespaced_dg_tag_key}' has"
              f" {len(dg_tag_value_actions)} planned Tag Values, exceeding the"
              " Google Cloud Resource Manager limit of"
              f" {constants.MAX_DG_TAG_VALUES_PER_TAG_KEY} Tag Values per Tag"
              " Key. [ACTION REQUIRED: Prune unused Policy Tags or split this"
              " taxonomy across multiple DG Tag Keys before running '--phase"
              " create'.]"
          )
          for value_index, value_action in enumerate(dg_tag_value_actions):
            if value_index >= constants.MAX_DG_TAG_VALUES_PER_TAG_KEY:
              value_action.setdefault("warnings", []).append(
                  f"Exceeds the {constants.MAX_DG_TAG_VALUES_PER_TAG_KEY}"
                  " Tag Values per DG Tag Key limit on"
                  f" '{namespaced_dg_tag_key}' (Tag Value"
                  f" #{value_index + 1}). [ACTION REQUIRED: Prune unused tags"
                  " or split the taxonomy before running '--phase create'.]"
              )

        cast(
            list[Any],
            plan["phase_2_resource_manifest"][
                constants.KEY_POLICY_TAGS_TO_DG_TAG_VALUES
            ],
        ).extend(dg_tag_value_actions)

        cast(
            dict[str, Any],
            plan["phase_3_binding_map"][
                constants.KEY_POLICY_TAGS_TO_DG_TAG_VALUES
            ],
        ).update(bindings_map)

        # Step 3c: Map Raw Reader Parity, Default Deny Parity, and V1 Data
        # Policies to V2 Data Policy creation actions.
        policy_tag_namespaced_values = {
            action["source_resource_name"]: action["namespaced_name"]
            for action in dg_tag_value_actions
            if "source_resource_name" in action and "namespaced_name" in action
        }
        (
            data_policy_actions,
            data_policy_target_count,
            data_policy_source_count,
        ) = _map_data_policies(
            taxonomy,
            policy_tag_short_names,
            policy_tag_display_paths,
            target_dgt_project_id,
            normalized_data_policy_projects,
            dg_tag_key_short_name,
            used_data_policy_ids_by_project,
            policy_tag_namespaced_values=policy_tag_namespaced_values,
        )
        target_data_policies += data_policy_target_count
        source_data_policies += data_policy_source_count

        # ======================================================================
        # Step 4: Partition Policies & Enforce 1,000-Policy per Tag Key Limit
        # ======================================================================
        # Partition generated V2 Data Policy actions into the 3 Phase 2a
        # execution lists first (`raw_reader_policies`, `default_deny_policies`,
        # `migrated_policies`) so the 1,000-policy service quota check runs in
        # the exact Phase 2a creation order rather than per-tag interleaved
        # order.
        raw_reader_policies = [
            action
            for action in data_policy_actions
            if action.get("source_entity_type")
            == constants.SOURCE_ENTITY_TYPE_POLICY_TAG
            and action.get("note") == constants.PARITY_RAW_READER
        ]
        default_deny_policies = [
            action
            for action in data_policy_actions
            if action.get("source_entity_type")
            == constants.SOURCE_ENTITY_TYPE_POLICY_TAG
            and action.get("note") == constants.PARITY_DEFAULT_DENY
        ]
        migrated_policies = [
            action
            for action in data_policy_actions
            if action.get("source_entity_type")
            != constants.SOURCE_ENTITY_TYPE_POLICY_TAG
        ]
        ordered_policy_actions = (
            raw_reader_policies + default_deny_policies + migrated_policies
        )

        # BigQuery Data Policy Service allows at most 1,000 V2 Data Policies per
        # DG Tag Key within a single project. Flag every individual policy at
        # index >= 1000 in Phase 2a creation order and attach a summary warning
        # to the parent Tag Key.
        for policy_action in ordered_policy_actions:
          policy_project_id = policy_action["target_project_id"]
          quota_key = (policy_project_id, namespaced_dg_tag_key)
          cumulative_index = data_policies_count_by_project_and_tag_key[
              quota_key
          ]
          data_policies_count_by_project_and_tag_key[quota_key] += 1
          if cumulative_index >= constants.MAX_DATA_POLICIES_PER_DG_TAG_KEY:
            policy_warning = (
                f"Data Policy '{policy_action['policy_id']}' exceeds the"
                f" limit of {constants.MAX_DATA_POLICIES_PER_DG_TAG_KEY} data"
                f" policies for DG Tag Key '{namespaced_dg_tag_key}' in"
                f" project '{policy_project_id}'. [ACTION REQUIRED:"
                " This policy cannot be created because the tag key limit is"
                " exhausted. Must resolve before proceeding.]"
            )
            policy_action.setdefault("warnings", []).append(policy_warning)

        for data_policy_project_id in normalized_data_policy_projects:
          total_policies_for_tag_key = (
              data_policies_count_by_project_and_tag_key[
                  (data_policy_project_id, namespaced_dg_tag_key)
              ]
          )
          if (
              total_policies_for_tag_key
              > constants.MAX_DATA_POLICIES_PER_DG_TAG_KEY
          ):
            limit_warning = (
                f"DG Tag Key '{namespaced_dg_tag_key}' is associated with"
                f" {total_policies_for_tag_key} data policies in project"
                f" '{data_policy_project_id}', which exceeds the BigQuery"
                " Data Policy Service limit of"
                f" {constants.MAX_DATA_POLICIES_PER_DG_TAG_KEY} policies per"
                " tag key in a project. [ACTION REQUIRED: Data Policy"
                " creation in Phase 2 will fail for policies beyond"
                f" {constants.MAX_DATA_POLICIES_PER_DG_TAG_KEY}. Any"
                " excessive data policies won't be created for a single DG"
                " tag key, causing an incomplete migration or security"
                " access leaks. You must split the taxonomy or consolidate"
                " policies before proceeding.]"
            )
            if limit_warning not in dg_tag_key_action.setdefault(
                "warnings", []
            ):
              dg_tag_key_action["warnings"].append(limit_warning)

        cast(
            list[Any],
            plan["phase_2_resource_manifest"][
                constants.KEY_POLICY_TAGS_TO_RAW_READER_DATA_POLICIES_V2
            ],
        ).extend(raw_reader_policies)
        cast(
            list[Any],
            plan["phase_2_resource_manifest"][
                constants.KEY_POLICY_TAGS_TO_DEFAULT_DENY_DATA_POLICIES_V2
            ],
        ).extend(default_deny_policies)
        cast(
            list[Any],
            plan["phase_2_resource_manifest"][
                constants.KEY_DATA_POLICIES_V1_TO_DATA_POLICIES_V2
            ],
        ).extend(migrated_policies)

    # ==========================================================================
    # Step 5: Populate Plan Summary Metrics & Validate DR Readiness
    # ==========================================================================
    if target_dg_tag_keys > constants.MAX_DG_TAG_KEYS_PER_PROJECT:
      plan.setdefault("warnings", []).append(
          f"Target project '{target_dgt_project_id}' has {target_dg_tag_keys}"
          " planned Data Governance Tag Keys, exceeding the Google Cloud"
          " Resource Manager limit of"
          f" {constants.MAX_DG_TAG_KEYS_PER_PROJECT} Tag Keys per project"
          " (shared across all Tag Keys in that project). [ACTION REQUIRED:"
          " Split taxonomies across multiple '--target-dgt-project-id'"
          " projects or prune unused taxonomies before running '--phase"
          " create'.]"
      )
    plan["plan_summary"]["total_taxonomies_mapped"] = target_dg_tag_keys
    plan["plan_summary"]["total_tags_to_create"] = target_dg_tag_values
    plan["plan_summary"]["total_policies_to_create"] = target_data_policies

    plan["plan_summary"]["source_metrics"][
        "total_taxonomies"
    ] = source_taxonomies
    plan["plan_summary"]["source_metrics"][
        "total_policy_tags"
    ] = source_policy_tags
    plan["plan_summary"]["source_metrics"][
        "total_data_policies"
    ] = source_data_policies

    plan["plan_summary"]["target_metrics"][
        "total_tag_keys"
    ] = target_dg_tag_keys
    plan["plan_summary"]["target_metrics"][
        "total_tag_values"
    ] = target_dg_tag_values
    plan["plan_summary"]["target_metrics"][
        "total_data_policies"
    ] = target_data_policies
    plan["plan_summary"]["target_metrics"]["total_raw_reader_policies"] = len(
        plan["phase_2_resource_manifest"][
            constants.KEY_POLICY_TAGS_TO_RAW_READER_DATA_POLICIES_V2
        ]
    )
    plan["plan_summary"]["target_metrics"]["total_default_deny_policies"] = len(
        plan["phase_2_resource_manifest"][
            constants.KEY_POLICY_TAGS_TO_DEFAULT_DENY_DATA_POLICIES_V2
        ]
    )
    plan["plan_summary"]["target_metrics"]["total_migrated_data_policies"] = (
        len(
            plan["phase_2_resource_manifest"][
                constants.KEY_DATA_POLICIES_V1_TO_DATA_POLICIES_V2
            ]
        )
    )

    self.validate_plan_dr_readiness(plan)
    return plan

  def generate_markdown_report(self, plan: dict[str, Any]) -> str:
    """Renders a human-readable Markdown summary report from a `plan` dict.

    Report Structure:
    1. Top-level metadata summary and Target Project Architecture & Disaster
       Recovery Readiness (`DR_WARN_02` guidance for Mode 1 vs. Mode 2, plus
       Separation-Only multi-region taxonomy rationale).
    2. Source Metrics vs. Target Metrics (including per-category V2 Data Policy
       counts and any `WARNING [CRITICAL]` 1,000-policy quota alerts).
    3. Five Proposed Entity Mapping tables wrapped in `<!-- mdformat off -->` /
       `<!-- mdformat on -->` comments so tables render cleanly in Markdown
       viewers and Google Docs:
       - Section 1: Taxonomies to DG Tag Keys
       - Section 2: Policy Tags to DG Tag Values
       - Section 3: Policy Tags to Data Policies (V2) - Raw Reader Parity
       - Section 4: Policy Tags to Data Policies (V2) - Default Deny Parity
       - Section 5: Data Policies (V1) to Data Policies (V2)
    4. Aggregated `### Warnings` section collecting both top-level regional
       errors and per-entity validation/DR warnings.

    Args:
        plan: Migration plan dictionary generated by `generate_plan`.

    Returns:
        Formatted Markdown report string.
    """
    metadata = plan.get("metadata", {})
    source_project_id = metadata.get("source_project_id", "")
    target_dgt_project_id = metadata.get("target_dgt_project_id", "")
    target_data_policy_mode = metadata.get(
        "target_data_policy_mode",
        constants.TARGET_DATA_POLICY_MODE_DEFAULT_PROJECT,
    )
    target_data_policy_project_ids = metadata.get(
        "target_data_policy_project_ids", []
    )
    collision_resolution = metadata.get(
        "collision_resolution", constants.COLLISION_RESOLUTION_COUNTER
    )
    source_regions = metadata.get("source_regions", [])

    report_lines = []
    report_lines.append(
        "# Policy Tag to Data Governance Tag Migration Plan Summary"
    )
    report_lines.append("")
    report_lines.append(
        f"- **Source Project:** {source_project_id} (Project with existing"
        " Policy Tags)"
    )
    report_lines.append(f"- **Source Region(s):** {', '.join(source_regions)}")
    report_lines.append(
        f"- **Target DG Tag Project:** {target_dgt_project_id} (Project where"
        " global Data Governance Tag Keys and Values will be created)"
    )
    report_lines.append(
        f"- **Target Data Policy Placement Mode:** {target_data_policy_mode}"
    )
    report_lines.append(
        "- **Target Data Policy Project(s):**"
        f" {', '.join(target_data_policy_project_ids)} (Project(s) where"
        " regional V2 Data Policies will be created)"
    )
    report_lines.append(
        f"- **Tag Key Collision Resolution Strategy:** {collision_resolution}"
    )

    report_lines.append("")
    report_lines.append(
        "### Target Project Architecture & Disaster Recovery Readiness"
    )
    report_lines.append("")
    report_lines.append(
        "- **Global Data Governance Tag Project (`--target-dgt-project-id`):**"
        f" `{target_dgt_project_id}`"
    )
    if (
        target_data_policy_mode
        == constants.TARGET_DATA_POLICY_MODE_DEFAULT_PROJECT
    ):
      default_project = (
          target_data_policy_project_ids[0]
          if target_data_policy_project_ids
          else ""
      )
      report_lines.append(
          "- **Data Policy Placement Mode (`--target-default-dp-project-id` -"
          f" Mode 1):** `{default_project}` (Organization-Level Default Data"
          " Policy Project)"
      )
      report_lines.append(
          "  - **Action Required for Query Evaluation & Disaster Recovery"
          f" [{constants.DR_WARN_02}]:**"
      )
      report_lines.append(
          "    - **Why:** BigQuery evaluates and replicates V2 Data Policies"
          " only from a table's parent project (`parentProject`) or projects"
          " configured in your Organization's `default_data_policy_projects`"
          " setting."
      )
      report_lines.append(
          f"    - **Required Action:** Register `{default_project}` in"
          " `default_data_policy_projects` in **both** your primary region(s)"
          f" ({', '.join(source_regions)}) and any target Disaster Recovery"
          " (Cross-Region Replication) secondary regions before switching"
          " enforcement or enabling dataset replication."
      )
    else:
      formatted_projects = ", ".join(
          f"`{project}`" for project in target_data_policy_project_ids
      )
      report_lines.append(
          "- **Data Policy Placement Mode (`--target-table-dp-project-ids` -"
          f" Mode 2):** {formatted_projects} (Data Table Parent Project(s))"
      )
      report_lines.append(
          "  - **Data Policy Lookup & Disaster Recovery Readiness"
          f" [{constants.DR_WARN_02}]:**"
      )
      report_lines.append(
          "    - **Placement:** Regional V2 Data Policies will be created"
          " directly inside each specified table parent project"
          f" ({formatted_projects}), all referencing the shared global Data"
          f" Governance Tags in `{target_dgt_project_id}`."
      )
      report_lines.append(
          "    - **Organization Config:** Because BigQuery automatically"
          " evaluates and replicates policies in each table's parent project,"
          " no Organization-level `default_data_policy_projects` configuration"
          " is required for tables residing in these projects."
      )
