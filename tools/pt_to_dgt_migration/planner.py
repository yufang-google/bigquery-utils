"""Phase 1b Migration Planner: maps Policy Tags to Data Governance Tags.

Architectural Role & Bigger-Picture Fit:
----------------------------------------
`planner.py` implements **Phase 1b (`--phase plan`)** of the 3-Phase migration
pipeline. It consumes the read-only regional discovery results produced by
Phase 1a (`Analyzer.analyze_static_taxonomies`) and synthesizes two artifacts:

1. `plan.json` (Machine-Readable Contract for Phases 2 and 3):
   - `metadata`: Source project/regions, target DGT project, target V2 Data
     Policy placement mode (`DEFAULT_DATA_POLICY_PROJECT` Mode 1 vs.
     `TABLE_PARENT_PROJECTS` Mode 2), collision resolution strategy, timestamp,
     and tool version.
   - `plan_summary`: Source vs. target resource counts (`total_tag_keys`,
     `total_tag_values`, `total_data_policies`, broken down into Raw Reader
     Parity, Default Deny Parity, and Migrated V1 Data Policies).
   - `phase_2_resource_manifest`: Five ordered action lists consumed by
     `Creator` (Phase 2a), `Deleter` (Phase 2b), and `Swapper` (Phase 3):
       1. `taxonomies_to_dg_tag_keys` (`CREATE_DG_TAG_KEY`)
       2. `policy_tags_to_dg_tag_values` (`CREATE_DG_TAG_VALUE`)
       3. `policy_tags_to_raw_reader_data_policies_v2` (`CREATE_DATA_POLICY_V2`)
       4. `policy_tags_to_default_deny_data_policies_v2`
          (`CREATE_DATA_POLICY_V2`)
       5. `data_policies_v1_to_data_policies_v2` (`CREATE_DATA_POLICY_V2`)
   - `phase_3_binding_map`: Bi-directional lookup table mapping each source
     Policy Tag resource name (`projects/<num>/locations/<loc>/taxonomies/<t>/`
     `policyTags/<pt>`) to its target DG Tag Key/Value (`{"dg_tag_key": ...,`
     `"dg_tag_value": ...}`), driving both forward table cutover (`pt-to-dgt`)
     and emergency rollback (`dgt-to-pt`) in Phase 3 (`Swapper`).
2. `plan_report.md` (Human-Readable Audit & Readiness Report):
   Generated by `Planner.generate_markdown_report(plan)` to give data
   governance administrators a complete pre-execution review of entity
   mappings, Disaster Recovery (`DR_WARN_01`..`DR_WARN_04`) instructions, and
   `[ACTION REQUIRED]` validation warnings.

Key Architectural Decisions, Alternatives Considered & Trade-Offs:
------------------------------------------------------------------
1. Separation-Only (1:1 Regional Taxonomy -> Global DG Tag Key) vs.
   Cross-Region Consolidation:
   - *Decision:* Every regional Policy Tag taxonomy maps 1:1 to its own separate
     global DG Tag Key in `--target-dgt-project-id`.
   - *Why Not Consolidate Across Regions?* First, legacy Policy Tags do not
     support BigQuery Cross-Region Replication (CRR), so same-named taxonomies
     in different regions today (e.g., `Sensitive Data` in `us` and `eu`) govern
     independent primary datasets with potentially different IAM principals.
     Second, during DGT Cross-Region Replication, BigQuery fails dataset
     replication if the secondary region already contains standalone
     user-created V2 Data Policies attached to the same DG Tag Key as the
     primary region's policies. Keeping regional taxonomies on separate global
     DG Tag Keys ensures each Tag Key has standalone policies in only its home
     region, allowing BigQuery CRR to automatically replicate those policies to
     any secondary region post-migration.
2. Non-Lossy Sanitization (`sanitize_name`) with Explicit Warnings:
   - *Decision:* `sanitize_name` only replaces spaces with `_` (since spaces are
     common in Policy Tag display names but forbidden in Resource Manager Tag
     `short_name`s). It deliberately does **not** strip invalid punctuation,
     pad leading/trailing hyphens, or silently truncate names exceeding 63
     characters.
   - *Trade-off:* Instead of guessing a lossy rename that could obscure lineage
     or collide unpredictably, `_validate_short_name` attaches an
     `[ACTION REQUIRED]` warning to `plan.json` so the customer explicitly
     chooses the compliant `short_name` before Phase 2a creation.
3. Three-Tier V2 Data Policy Synthesis for Access Control Parity:
   - *Policy 1 (Raw Reader Parity):* Migrates `fineGrainedReader` principals to
     `RAW_DATA_ACCESS_POLICY` `grantees`. Taxonomy-level readers are attached
     to **Root Tag Values** and any non-root Tag Value carrying a direct
     `DATA_MASKING_POLICY` so descendant tags inherit access via BigQuery's
     hierarchical evaluation (`column.matchTagHierarchy`) without overriding
     raw precedence or duplicating policies on every child node.
   - *Policy 2 (Fail-Closed Default Deny Seatbelt):* Synthesizes a permanent
     `_default_deny` `RAW_DATA_ACCESS_POLICY` (`grantees: []`) on **every** Tag
     Value in an access-controlled taxonomy (`is_access_control=True`), ensuring
     DGT columns (which are Fail-Open when no policy is attached) remain
     strictly Fail-Closed even if raw-reader or masking policies are deleted
     later.
   - *Policy 3 (Migrated V1 Data Policies):* Translates existing V1 Data
     Policies (`DATA_MASKING_POLICY` predefined expressions/custom routines and
     `COLUMN_LEVEL_SECURITY_POLICY` / `RAW_DATA_ACCESS_POLICY`) into V2 Data
     Policies.
"""

