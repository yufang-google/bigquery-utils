def sanitize_name(
    name: str, space_replacement: str = "_", collapse_spaces: bool = True
) -> str:
  """Sanitizes a display name to be used as a DG Tag Key/Value short name.

  Design Decision (Minimal, Non-Lossy Sanitization):
  Data Catalog allows spaces in Taxonomy and Policy Tag `display_name`s (e.g.,
  `"Sensitive Data"`), whereas Google Cloud Resource Manager forbids spaces in
  TagKey/TagValue `short_name`s. This helper replaces spaces with
  `space_replacement` (`"_"` by default) while intentionally leaving other
  characters, leading/trailing symbols, and lengths > 63 characters untouched.
  Any remaining compliance issues are surfaced as `[ACTION REQUIRED]` warnings
  by `_validate_short_name` so operators can review and customize the name in
  `plan.json` rather than suffering silent truncation or lossy character
  stripping.

  Args:
      name: The source Taxonomy or Policy Tag display name to sanitize.
      space_replacement: Replacement string for spaces (default: `"_"`).
      collapse_spaces: If True, collapses consecutive spaces into a single
        replacement token; if False, replaces each space character 1:1.

  Returns:
      The space-sanitized short name candidate.
  """
  pattern = r" +" if collapse_spaces else r" "
  name = re.sub(pattern, space_replacement, name)
  return name


def sanitize_data_policy_id(policy_id: str) -> str:
  """Sanitizes a candidate V2 Data Policy ID to `[a-zA-Z0-9_]`.

  Why This Differs from `sanitize_name`:
  Resource Manager Tag `short_name`s allow hyphens (`-`) and dots (`.`), whereas
  BigQuery Data Policy Service V2 strictly restricts `data_policy_id` to ASCII
  letters, digits, and underscores (`^[a-zA-Z0-9_]{1,200}$`). Because V2 Data
  Policy IDs are synthesized by concatenating `migrated_raw_` or
  `migrated_masking_` with the Tag Key and Tag Value short names (which may
  contain hyphens or dots), this helper converts all non-`[a-zA-Z0-9_]`
  characters to underscores (`_`).

  Args:
      policy_id: The candidate V2 Data Policy ID string.

  Returns:
      The sanitized Data Policy ID containing only ASCII alphanumerics and `_`.
  """
  return re.sub(r"[^a-zA-Z0-9_]", "_", policy_id)


def _validate_short_name(name: str) -> list[str]:
  """Validates a DG Tag Key/Value `short_name` against Resource Manager rules.

  Enforces the Safe Harbor character and length rules required by Google Cloud
  Resource Manager for TagKey and TagValue `short_name`s:
  1. Non-empty and at most 63 characters (`1 <= len(name) <= 63`).
  2. Starts and ends with a strict ASCII alphanumeric character (`[a-zA-Z0-9]`).
  3. Contains only ASCII letters, digits, hyphens (`-`), underscores (`_`), or
     dots (`.`).

  Args:
      name: The sanitized DG Tag Key or Tag Value `short_name` candidate.

  Returns:
      List of human-readable `[ACTION REQUIRED]` warning strings (empty if the
      name is 100% valid).
  """
  warnings = []
  instruction = (
      " [ACTION REQUIRED: This issue will cause DGT creation to fail. Must"
      " resolve before proceeding.]"
  )
  if not name:
    warnings.append("Name is empty." + instruction)
    return warnings

  if len(name) > 63:
    warnings.append(
        f"Name exceeds 63 characters (length: {len(name)})." + instruction
    )

  # Python's `str.isalnum()` returns True for non-ASCII Unicode letters (such as
  # accented characters). Combining `.isascii()` with `.isalnum()` enforces the
  # strict `[a-zA-Z0-9]` start/end boundary required by Resource Manager.
  if not (name[0].isascii() and name[0].isalnum()):
    warnings.append(
        "Name must start with an alphanumeric character (a-z, A-Z, 0-9)."
        + instruction
    )

  if not (name[-1].isascii() and name[-1].isalnum()):
    warnings.append(
        "Name must end with an alphanumeric character (a-z, A-Z, 0-9)."
        + instruction
    )

  # Validate against the Safe Harbor character set: `[a-zA-Z0-9\-_\.]`.
  invalid_chars = set(re.findall(r"[^a-zA-Z0-9\-\_\.]", name))
  if invalid_chars:
    char_list = ["' '" if c == " " else f"'{c}'" for c in sorted(invalid_chars)]
    warnings.append(
        f"Name contains potentially invalid characters: {', '.join(char_list)}"
        + instruction
    )

  return warnings


def _format_dg_tag_key_note(dg_tag_key_action: dict[str, Any]) -> str:
  """Formats the Markdown report note cell for a planned DG Tag Key row."""
  explicit_note = str(dg_tag_key_action.get("note", ""))
  if explicit_note:
    return explicit_note
  source_name = str(dg_tag_key_action.get("source_display_name", ""))
  source_region = str(dg_tag_key_action.get("source_taxonomy_region", ""))
  short_name = str(
      dg_tag_key_action.get("api_payload", {}).get("short_name", "")
  )
  if not short_name:
    namespaced = str(dg_tag_key_action.get("namespaced_name", ""))
    short_name = namespaced.split("/")[-1] if "/" in namespaced else ""
  sanitized_source = sanitize_name(source_name)
  sanitized_region = sanitize_name(source_region) if source_region else ""
  collision_suffix = ""
  if (
      sanitized_source
      and sanitized_region
      and (
          short_name == f"{sanitized_source}_from_{sanitized_region}"
          or short_name.startswith(
              f"{sanitized_source}_from_{sanitized_region}-"
          )
      )
  ):
    collision_suffix = " (Collision resolved via from_region)"
  elif (
      sanitized_source
      and short_name != sanitized_source
      and re.fullmatch(
          rf"{re.escape(sanitized_source)}-\d+",
          short_name,
      )
  ):
    collision_suffix = " (Collision resolved via counter)"
  if source_region:
    return f"Source region: {source_region}{collision_suffix}"
  return collision_suffix.strip()


def _format_dg_tag_value_note(dg_tag_value_action: dict[str, Any]) -> str:
  """Formats the Markdown report note cell for a planned DG Tag Value row."""
  explicit_note = str(dg_tag_value_action.get("note", ""))
  if explicit_note:
    return explicit_note
  source_path = str(dg_tag_value_action.get("source_display_path", ""))
  leaf_display = source_path.split(" > ")[-1] if source_path else ""
  sanitized_leaf = sanitize_name(leaf_display)
  short_name = str(
      dg_tag_value_action.get("api_payload", {}).get("short_name", "")
  )
  if not short_name:
    namespaced = str(dg_tag_value_action.get("namespaced_name", ""))
    short_name = namespaced.split("/")[-1] if "/" in namespaced else ""
  if (
      sanitized_leaf
      and short_name != sanitized_leaf
      and re.fullmatch(
          rf"{re.escape(sanitized_leaf)}-\d+",
          short_name,
      )
  ):
    return "Collision resolved via counter"
  return ""


def _format_target_policy_entity(data_policy_action: dict[str, Any]) -> str:
  """Prefixes a planned V2 Data Policy ID with its `target_project_id`."""
  policy_project = data_policy_action.get("target_project_id", "")
  policy_id = data_policy_action["policy_id"]
  return f"{policy_project}/{policy_id}" if policy_project else policy_id


def _format_raw_reader_parity_note(
    data_policy_action: dict[str, Any],
    friendly_note_labels: dict[str, str],
) -> str:
  """Formats provenance and custom-role details for a Raw Reader Parity row."""
  raw_note = (
      data_policy_action.get("note")
      or data_policy_action.get("migration_type")
      or ""
  )
  base_note = friendly_note_labels.get(raw_note, raw_note)
  audit_lineage = str(data_policy_action.get("audit_lineage", ""))
  custom_role_detail = ""
  marker = f"({constants.PARITY_RAW_READER}; "
  if marker in audit_lineage and audit_lineage.endswith(")"):
    start_idx = audit_lineage.index(marker) + len(marker)
    custom_role_detail = f"; {audit_lineage[start_idx:-1]}"
  if " and Taxonomy:" in audit_lineage:
    return f"{base_note} (from Policy Tag & Taxonomy IAM{custom_role_detail})"
  if audit_lineage.startswith("Migrated from Taxonomy:"):
    return f"{base_note} (from Taxonomy IAM{custom_role_detail})"
  if audit_lineage.startswith("Migrated from Policy Tag:"):
    return f"{base_note} (from Policy Tag IAM{custom_role_detail})"
  return base_note


def _convert_to_iam_v3_principal(principal: str) -> str:
  """Converts an IAM v1 policy member string to an IAM v3 principal URI.

  Why Conversion Is Required:
  Legacy Data Catalog Policy Tag IAM policies and V1 Data Policy IAM policies
  store principals in IAM v1 format (`user:alice@example.com`,
  `group:team@example.com`, `serviceAccount:sa@proj.iam.gserviceaccount.com`),
  whereas BigQuery V2 Data Policies store grantees inline using IAM v3 /
  Next-Gen principal URIs (`principal://...` and `principalSet://...`).

  Handling of Unsupported / Tombstoned Principals:
  Principals that are already in `principal://` or `principalSet://` format
  (such as Workforce Identity, Workload Identity, or BigQuery authorized views /
  datasets) are preserved as-is. Principals with `deleted:` (tombstoned
  accounts) or `domain:` prefixes are intentionally returned unchanged so
  `_validate_grantees` can flag them with explicit `[ACTION REQUIRED]` warnings
  rather than producing invalid V2 grantee URIs.

  Args:
      principal: Source IAM v1 or v3 principal string from `Analyzer`.

  Returns:
      Converted IAM v3 principal URI (or the original string if unconverted).
  """
  if principal.startswith("principal://") or principal.startswith(
      "principalSet://"
  ):
    return principal
  if principal.startswith("user:"):
    subject = principal.removeprefix("user:")
    return f"principal://goog/subject/{subject}"
  elif principal.startswith("group:"):
    group = principal.removeprefix("group:")
    return f"principalSet://goog/group/{group}"
  elif principal.startswith("serviceAccount:"):
    service_account_email = principal.removeprefix("serviceAccount:")
    return (
        "principal://iam.googleapis.com/projects/-/serviceAccounts/"
        f"{service_account_email}"
    )
  return principal


def _validate_grantees(
    grantees: list[str], context_label: str = ""
) -> list[str]:
  """Validates converted V2 Data Policy grantees for unsupported formats/limits.

  Detects four categories of source IAM bindings that cannot be provisioned in a
  BigQuery V2 Data Policy `grantees` list:
  1. Tombstoned principals (`deleted:user:...`, `deleted:serviceAccount:...`),
     which occur when a Google account or service account was deleted without
     cleaning up legacy Policy Tag IAM bindings.
  2. Unsupported principal prefixes (such as `domain:example.com`, `allUsers`,
     or `allAuthenticatedUsers`) that do not map to `principal://` or
     `principalSet://` URIs accepted by the V2 Data Policy API.
  3. BigQuery Authorized Routine principals (`.../routines/...`), which BigQuery
     V2 Data Policy `grantees` reject with `INVALID_ARGUMENT`.
  4. IAM v3 Access Policy compilation limits exceeding `500` distinct IAM
     principals (`MAX_GRANTEES_PER_DATA_POLICY_V2`) or `100` distinct group/pool
     `principalSet://` principals (`MAX_GROUP_GRANTEES_PER_DATA_POLICY_V2`),
     excluding BigQuery view/dataset catalog URIs.

  Args:
      grantees: List of principal strings after `_convert_to_iam_v3_principal`.
      context_label: Optional source Policy Tag display path or V1 Data Policy
        short name for inclusion in the warning message.

  Returns:
      List of `[ACTION REQUIRED]` warning strings for any invalid grantees.
  """
  warnings = []
  context_suffix = f" on '{context_label}'" if context_label else ""
  distinct_iam_principals: set[str] = set()
  distinct_group_principals: set[str] = set()
  for grantee in grantees:
    if grantee.startswith("deleted:"):
      warnings.append(
          f"Tombstoned IAM principal '{grantee}'{context_suffix} cannot be"
          " migrated to a V2 Data Policy. [ACTION REQUIRED: Remove or update"
          " this deleted principal in the migration plan before running"
          " '--phase create'.]"
      )
    elif not grantee.startswith(("principal://", "principalSet://")):
      warnings.append(
          f"Unsupported IAM principal format '{grantee}'{context_suffix} for"
          " V2 Data Policy grantees (expected 'principal://' or"
          " 'principalSet://'). [ACTION REQUIRED: Remove or convert this"
          " principal in the migration plan before running '--phase"
          " create'.]"
      )
    elif "/routines/" in grantee:
      warnings.append(
          f"BigQuery Authorized Routine principal '{grantee}'"
          f"{context_suffix} is not supported in V2 Data Policy grantees"
          " (rejected with INVALID_ARGUMENT). [ACTION REQUIRED: Remove this"
          " Authorized Routine principal from grantees and grant routine"
          " callers access directly before running '--phase create'.]"
      )
    elif "/datasets/" not in grantee and "/views/" not in grantee:
      distinct_iam_principals.add(grantee)
      if grantee.startswith("principalSet://"):
        distinct_group_principals.add(grantee)

  if len(distinct_iam_principals) > constants.MAX_GRANTEES_PER_DATA_POLICY_V2:
    warnings.append(
        f"IAM principal count ({len(distinct_iam_principals)}){context_suffix}"
        " exceeds BigQuery's V2 Data Policy limit of"
        f" {constants.MAX_GRANTEES_PER_DATA_POLICY_V2} distinct IAM principals"
        " per policy. [ACTION REQUIRED: Consolidate individual user or service"
        " account principals into Google Groups before running '--phase"
        " create'.]"
    )
  if (
      len(distinct_group_principals)
      > constants.MAX_GROUP_GRANTEES_PER_DATA_POLICY_V2
  ):
    warnings.append(
        f"Group/principalSet count ({len(distinct_group_principals)})"
        f"{context_suffix} exceeds BigQuery's V2 Data Policy limit of"
        f" {constants.MAX_GROUP_GRANTEES_PER_DATA_POLICY_V2} distinct"
        " principalSet:// groups per policy. [ACTION REQUIRED: Consolidate"
        " groups into nested parent Google Groups before running '--phase"
        " create'.]"
    )
  return warnings


def _validate_data_policy_id(policy_id: str) -> list[str]:
  """Validates a V2 `data_policy_id` against BigQuery Data Policy API limits.

  BigQuery Data Policy Service V2 requires `data_policy_id` to be non-empty,
  at most 200 characters (`1 <= len(policy_id) <= 200`), and composed strictly
  of ASCII letters, digits, and underscores (`^[a-zA-Z0-9_]+$`). Following the
  same non-lossy philosophy as `_validate_short_name`, overlong IDs are flagged
  with an `[ACTION REQUIRED]` warning rather than silently truncated.

  Args:
      policy_id: Candidate V2 `data_policy_id` string.

  Returns:
      List of `[ACTION REQUIRED]` warning strings (empty if valid).
  """
  warnings = []
  instruction = (
      " [ACTION REQUIRED: This issue will cause Data Policy creation to fail."
      " Must resolve manually before proceeding.]"
  )
  if not policy_id:
    warnings.append("Data Policy ID is empty." + instruction)
    return warnings

  if len(policy_id) > 200:
    warnings.append(
        f"Data Policy ID exceeds 200 characters (length: {len(policy_id)})."
        + instruction
    )

  if not re.fullmatch(r"[a-zA-Z0-9_]+", policy_id):
    warnings.append(
        "Data Policy ID contains invalid characters. Only letters, numbers, and"
        " underscores are allowed."
        + instruction
    )
  return warnings


